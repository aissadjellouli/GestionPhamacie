using System.Text;

namespace Pharma.Architecture.Tests;

/// <summary>
/// Nom de la copie pour la réplication synchrone (2026-11-25, constat de l'essai réel) : « pg_basebackup -R » n'écrit pas
/// application_name ; sans lui, le principal (synchronous_standby_names = 'second_serveur') ne voit jamais la copie comme synchrone.
/// Set-NomCopieSynchrone (scripts/second-serveur/commun.ps1) est exécutée sous Windows PowerShell sur un postgresql.auto.conf au format
/// réel de pg_basebackup -R (PostgreSQL 18), dans un dossier jetable ; aucune base n'est touchée.
/// </summary>
public class NomCopieSynchroneTests
{
    // Ligne relevée telle qu'écrite par pg_basebackup -R le 2026-11-25 (apostrophes du passfile doublées)
    private const string Conninfo =
        "primary_conninfo = 'user=pharma_replication passfile=''C:\\\\Users\\\\x\\\\AppData\\\\Roaming/postgresql/pgpass.conf'' channel_binding=prefer "
        + "host=192.168.1.20 port=5432 sslmode=prefer sslnegotiation=postgres sslcompression=0 sslcertmode=allow sslsni=1 "
        + "ssl_min_protocol_version=TLSv1.2 gssencmode=disable krbsrvname=postgres gssdelegation=0 target_session_attrs=any load_balance_hosts=disable'";

    private static readonly string[] AutoConf =
    [
        "# Do not edit this file manually!",
        "# It will be overwritten by the ALTER SYSTEM command.",
        "synchronous_standby_names = 'second_serveur'",
        "synchronous_commit = 'local'",
        Conninfo,
        "primary_slot_name = 'second_serveur'",
    ];

    private static bool EssaiPossible => OperatingSystem.IsWindows();

    private static string Racine() => BaseJetableM4.RacineDepot();

    private static (int Code, string Sortie) Lancer(string dossier)
    {
        var commun = Path.Combine(Racine(), "scripts", "second-serveur", "commun.ps1");
        var info = new System.Diagnostics.ProcessStartInfo("powershell.exe")
        {
            RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false,
            StandardOutputEncoding = Encoding.UTF8,
        };
        foreach (var a in new[] { "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command",
                     $"[Console]::OutputEncoding = [Text.Encoding]::UTF8; . '{commun}'; Set-NomCopieSynchrone '{dossier}' 'second_serveur'" })
            info.ArgumentList.Add(a);
        using var p = System.Diagnostics.Process.Start(info)!;
        var sortie = p.StandardOutput.ReadToEndAsync();
        var erreur = p.StandardError.ReadToEndAsync();
        if (!p.WaitForExit(60_000)) { p.Kill(true); throw new TimeoutException("Set-NomCopieSynchrone n'a pas terminé."); }
        Task.WaitAll(sortie, erreur);
        return (p.ExitCode, sortie.Result + erreur.Result);
    }

    [Fact]
    public void Nom_ajoute_une_seule_fois_dans_primary_conninfo_sans_BOM_ni_autre_changement()
    {
        if (!EssaiPossible) return;
        var dossier = Directory.CreateTempSubdirectory("nom-copie-").FullName;
        try
        {
            var fichier = Path.Combine(dossier, "postgresql.auto.conf");
            File.WriteAllLines(fichier, AutoConf, new UTF8Encoding(false));

            var (code, sortie) = Lancer(dossier);
            Assert.Equal(0, code);
            Assert.Contains("ajouté", sortie);
            var lignes = File.ReadAllLines(fichier);
            Assert.Equal(AutoConf.Length, lignes.Length);
            Assert.Equal(Conninfo[..^1] + " application_name=second_serveur'", lignes[4]);
            Assert.Equal(AutoConf.Where((_, i) => i != 4), lignes.Where((_, i) => i != 4));   // le reste intact
            Assert.False(File.ReadAllBytes(fichier).AsSpan().StartsWith(new byte[] { 0xEF, 0xBB, 0xBF }));   // PostgreSQL : pas de BOM

            // Relancé (script rejoué) : rien n'est ajouté une seconde fois
            var (code2, sortie2) = Lancer(dossier);
            Assert.Equal(0, code2);
            Assert.Contains("déjà présent", sortie2);
            Assert.Single(System.Text.RegularExpressions.Regex.Matches(File.ReadAllText(fichier), "application_name="));
        }
        finally { Directory.Delete(dossier, true); }
    }

    [Fact]
    public void Copie_sans_primary_conninfo_refusee_sans_rien_ecrire()
    {
        if (!EssaiPossible) return;
        var dossier = Directory.CreateTempSubdirectory("nom-copie-").FullName;
        try
        {
            var fichier = Path.Combine(dossier, "postgresql.auto.conf");
            File.WriteAllLines(fichier, AutoConf.Where(l => !l.StartsWith("primary_conninfo")), new UTF8Encoding(false));
            var avant = File.ReadAllBytes(fichier);
            var (code, sortie) = Lancer(dossier);
            Assert.NotEqual(0, code);
            Assert.Contains("primary_conninfo absent", sortie);
            Assert.Equal(avant, File.ReadAllBytes(fichier));
        }
        finally { Directory.Delete(dossier, true); }
    }

    [Fact]
    public void Les_deux_scripts_qui_creent_la_copie_ajoutent_le_nom_avant_de_demarrer_PostgreSQL()
    {
        foreach (var nom in new[] { "initialiser-second-serveur.ps1", "remettre-en-second.ps1" })
        {
            var script = File.ReadAllText(Path.Combine(Racine(), "scripts", "second-serveur", nom));
            var copie = script.IndexOf("-X stream -R -P -w", StringComparison.Ordinal);
            var ajout = script.IndexOf("Set-NomCopieSynchrone $DossierDonnees $Slot", StringComparison.Ordinal);
            var demarrage = script.IndexOf("Start-Service $ServicePg", ajout, StringComparison.Ordinal);
            Assert.True(copie > 0 && ajout > copie && demarrage > ajout, nom);
        }
    }
}
